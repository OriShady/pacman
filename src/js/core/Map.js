    render(ctx) {
        for (let row = 0; row < this.grid.length; row++) {
            for (let col = 0; col < this.grid[row].length; col++) {
                const cell = this.grid[row][col];
                const x = col * TILE_SIZE;
                const y = row * TILE_SIZE;

                if (cell === TILE_TYPE.WALL) {
                    ctx.fillStyle = '#241434';
                    ctx.fillRect(x, y, TILE_SIZE, TILE_SIZE);
                    ctx.strokeStyle = '#5a189a';
                    ctx.lineWidth = 1;
                    ctx.strokeRect(x + 0.5, y + 0.5, TILE_SIZE - 1, TILE_SIZE - 1);
                } else if (cell === TILE_TYPE.PHASE_GATE) {
                    ctx.strokeStyle = '#70e000';
                    ctx.lineWidth = 2;
                    ctx.beginPath();
                    ctx.moveTo(x, y + TILE_SIZE / 2);
                    ctx.lineTo(x + TILE_SIZE, y + TILE_SIZE / 2);
                    ctx.stroke();
                } else if (cell === TILE_TYPE.DOT) {
                    ctx.fillStyle = '#ffb703';
                    ctx.beginPath();
                    ctx.arc(x + TILE_SIZE / 2, y + TILE_SIZE / 2, 2.5, 0, Math.PI * 2);
                    ctx.fill();
                } else if (cell === TILE_TYPE.ENERGIZER) {
                    ctx.fillStyle = '#70e000';
                    ctx.shadowBlur = 8;
                    ctx.shadowColor = '#70e000';
                    ctx.beginPath();
                    ctx.arc(x + TILE_SIZE / 2, y + TILE_SIZE / 2, 5, 0, Math.PI * 2);
                    ctx.fill();
                    ctx.shadowBlur = 0;
                }
            }
        }
    }

    isWall(col, row, inPhase = false, isGhost = false) {
        if (row === 14 && (col < 0 || col >= this.grid[0].length)) {
            return false;
        }

        if (row < 0 || row >= this.grid.length || col < 0 || col >= this.grid[0].length) {
            return true;
        }

        const cell = this.grid[row][col];
        if (cell === TILE_TYPE.WALL) return true;
        // Los fantasmas y Pac-Man en fase pueden cruzar la puerta espectral
        if (cell === TILE_TYPE.PHASE_GATE) return !(inPhase || isGhost);
        return false;
    }
